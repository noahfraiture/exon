local t = require('test.testutil')
local n = require('test.functional.testnvim')()
local Screen = require('test.functional.ui.screen')
local describe, it, before_each = t.describe, t.it, t.before_each
local eq, matches = t.eq, t.matches
local api, command, feed, exec_lua = n.api, n.command, n.feed, n.exec_lua

local function text(lines)
  api.nvim_buf_set_lines(0, 0, -1, true, lines)
  api.nvim_win_set_cursor(0, { 1, 0 })
end

local function selected()
  return exec_lua([[
    local values = {}
    for _, s in ipairs(vim.api.nvim_helix_get_state(0).selections) do
      values[#values + 1] = table.concat(vim.api.nvim_buf_get_text(0, s[1], s[2], s[3], s[4], {}), '\n')
    end
    return values
  ]])
end

describe('native Helix mode', function()
  before_each(function()
    n.clear()
  end)

  it('is opt-in and retains ordinary Vim behavior by default', function()
    eq(false, api.nvim_get_option_value('helix', {}))
    text({ 'one two three' })
    feed('w')
    eq('n', api.nvim_get_mode().mode)
    eq({ 1, 4 }, api.nvim_win_get_cursor(0))
    feed('dw')
    eq('one three', api.nvim_get_current_line())
  end)

  for _, multigrid in ipairs({ false, true }) do
    describe('mouse (multigrid=' .. tostring(multigrid) .. ')', function()
      before_each(function()
        Screen.new(40, 10, { ext_multigrid = multigrid })
        command('set mouse=a mousemodel=extend laststatus=0 scrolloff=0 sidescrolloff=0 nowrap')
        command('set mousescroll=ver:2,hor:4')
      end)

      local function mouse(button, action, row, col, modifiers)
        api.nvim_input_mouse(button, action, modifiers or '', 0, row, col)
        n.poke_eventloop()
      end

      it('moves the selection to a clicked character and cancels pending commands', function()
        text({ 'one two', 'three four' })
        command('set helix')
        api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 1, 0, 1, 5, true } }, 1, true)
        feed('mi')
        mouse('left', 'press', 1, 6)
        mouse('left', 'release', 1, 6)
        eq({ 2, 6 }, api.nvim_win_get_cursor(0))
        eq({ 'f' }, selected())
        eq('', exec_lua('return vim.helix.get_state().pending'))
        feed('cX<Esc>')
        eq({ 'one two', 'three Xour' }, api.nvim_buf_get_lines(0, 0, -1, true))
        feed('u')
        eq({ 'one two', 'three four' }, api.nvim_buf_get_lines(0, 0, -1, true))
      end)

      it('handles terminal mouse keys and clicking the existing primary', function()
        text({ 'one two', 'three four' })
        command('set helix')
        api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, true }, { 1, 0, 1, 5, false } }, 1, false)
        feed('<LeftMouse><0,0><LeftRelease><0,0>')
        eq({ 'o' }, selected())
        feed('<LeftMouse><6,1><LeftRelease><6,1>')
        eq({ 'f' }, selected())
      end)

      it('scrolls vertically without losing other selections or snapping the view back', function()
        local lines = {}
        for i = 1, 30 do
          lines[i] = ('line %02d'):format(i)
        end
        text(lines)
        command('set helix')
        local original = { { 4, 0, 4, 4, true }, { 24, 0, 24, 4, false } }
        api.nvim_helix_set_selections(0, original, 1, false)
        mouse('wheel', 'down', 0, 0)
        eq(3, n.fn.winsaveview().topline)
        eq(original, api.nvim_helix_get_state(0).selections)
        mouse('wheel', 'up', 0, 0)
        eq(1, n.fn.winsaveview().topline)
        for _ = 1, 5 do
          mouse('wheel', 'down', 0, 0)
        end
        eq(11, n.fn.winsaveview().topline)
        local state = api.nvim_helix_get_state(0)
        eq(2, #state.selections)
        eq(original[2], state.selections[2])
        eq(api.nvim_win_get_cursor(0)[1] - 1, state.selections[state.primary][1])
        eq('h', api.nvim_get_mode().mode)
      end)

      it('scrolls horizontally through the native wheel handler', function()
        text({ string.rep('word ', 30) })
        command('set helix')
        mouse('wheel', 'right', 0, 0)
        eq(4, n.fn.winsaveview().leftcol)
        mouse('wheel', 'left', 0, 0)
        eq(0, n.fn.winsaveview().leftcol)
      end)

      it('returns a dragged selection to Helix editing on release', function()
        text({ 'one two three' })
        command('set helix')
        mouse('left', 'press', 0, 4)
        mouse('left', 'drag', 0, 6)
        eq({ 1, 6 }, api.nvim_win_get_cursor(0))
        eq('v', api.nvim_get_mode().mode)
        mouse('left', 'release', 0, 6)
        eq('h', api.nvim_get_mode().mode)
        eq({ 'two' }, selected())
        feed('cX<Esc>')
        eq('one X three', api.nvim_get_current_line())
        feed('u')
        eq('one two three', api.nvim_get_current_line())
        eq({ 'two' }, selected())
      end)

      it('keeps native reverse and exclusive drag boundaries with Unicode', function()
        text({ 'one été three' })
        command('set helix selection=inclusive')
        mouse('left', 'press', 0, 6)
        mouse('left', 'drag', 0, 4)
        mouse('left', 'release', 0, 4)
        eq({ 'été' }, selected())
        eq(true, api.nvim_helix_get_state(0).selections[1][5])
        command('set selection=exclusive')
        mouse('left', 'press', 0, 4)
        mouse('left', 'drag', 0, 7)
        mouse('left', 'release', 0, 7)
        eq({ 'été' }, selected())
      end)

      it('adopts double-clicked words and triple-clicked lines on release', function()
        text({ 'one two three', 'four five' })
        command('set helix mousetime=10000')
        mouse('left', 'press', 0, 5)
        mouse('left', 'release', 0, 5)
        mouse('left', 'press', 0, 5)
        mouse('left', 'release', 0, 5)
        eq({ 'two' }, selected())
        eq('h', api.nvim_get_mode().mode)
        mouse('left', 'press', 0, 5)
        mouse('left', 'release', 0, 5)
        eq({ 'one two three\n' }, selected())
        eq('h', api.nvim_get_mode().mode)
      end)

      it(
        'scrolls an inactive window and clicks into it without changing the other selection',
        function()
          local lines = {}
          for i = 1, 30 do
            lines[i] = ('line %02d'):format(i)
          end
          text(lines)
          command('set helix')
          local right = api.nvim_get_current_win()
          local original = { { 4, 0, 4, 4, true }, { 24, 0, 24, 4, false } }
          api.nvim_helix_set_selections(right, original, 1, false)
          command('leftabove vsplit')
          local left = api.nvim_get_current_win()
          api.nvim_helix_set_selections(left, original, 1, false)
          api.nvim_set_current_win(right)
          mouse('wheel', 'down', 0, 0)
          eq(right, api.nvim_get_current_win())
          eq(original, api.nvim_helix_get_state(right).selections)
          eq(original, api.nvim_helix_get_state(left).selections)
          eq(3, exec_lua('return vim.api.nvim_win_call(..., vim.fn.winsaveview).topline', left))
          mouse('left', 'press', 0, 2)
          mouse('left', 'release', 0, 2)
          eq(left, api.nvim_get_current_win())
          eq({ { 2, 2, 2, 3, false } }, api.nvim_helix_get_state(left).selections)
          eq(original, api.nvim_helix_get_state(right).selections)
        end
      )

      it('honors Helix mouse mappings before native defaults', function()
        text({ 'one two' })
        command('set helix')
        exec_lua([[vim.keymap.set('h', '<LeftMouse>', function() vim.g.clicked = true end)]])
        mouse('left', 'press', 0, 5)
        eq(true, api.nvim_get_var('clicked'))
        eq({ 1, 0 }, api.nvim_win_get_cursor(0))
      end)

      it('leaves native Insert mouse movement usable with multiple cursors', function()
        text({ 'one two', 'three four' })
        command('set helix')
        api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 1, 0, 1, 5, false } }, 1, false)
        feed('iX')
        mouse('left', 'press', 0, 5)
        mouse('left', 'release', 0, 5)
        eq('i', api.nvim_get_mode().mode)
        feed('Y<Esc>')
        eq('h', api.nvim_get_mode().mode)
        eq(2, #api.nvim_helix_get_state(0).selections)
        -- Native Insert clicks reposition the primary only; typing still uses both cursors.
        eq({ 'Xone Ytwo', 'XYthree four' }, api.nvim_buf_get_lines(0, 0, -1, true))
      end)
    end)
  end

  it('opens indented lines using native o and O at every cursor', function()
    text({ '  one', '    two' })
    command('set helix autoindent expandtab shiftwidth=2')
    local original = { { 0, 2, 0, 5, false }, { 1, 4, 1, 7, true } }
    api.nvim_helix_set_selections(0, original, 2, false)
    feed('oX<Esc>')
    eq({ '  one', '  X', '    two', '    X' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'X', 'X' }, selected())
    eq(2, api.nvim_helix_get_state(0).primary)
    feed('u')
    eq({ '  one', '    two' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq(original, api.nvim_helix_get_state(0).selections)
    feed('OY<Esc>')
    eq({ '  Y', '  one', '    Y', '    two' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'Y', 'Y' }, selected())
    feed('u')
    eq({ '  one', '    two' }, api.nvim_buf_get_lines(0, 0, -1, true))
  end)

  it('uses native I and A to insert before indentation and after lines', function()
    text({ '  one', '    two' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 3, 0, 4, false }, { 1, 5, 1, 6, false } }, 1, false)
    feed('IX<Esc>')
    eq({ '  Xone', '    Xtwo' }, api.nvim_buf_get_lines(0, 0, -1, true))
    feed('AY<Esc>')
    eq({ '  XoneY', '    XtwoY' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'Y', 'Y' }, selected())
  end)

  it(
    'indents selected lines once with native options and retains selections through undo',
    function()
      text({ 'one two', 'three', 'four', 'five' })
      command('set helix expandtab shiftwidth=2')
      local original = {
        { 0, 0, 0, 3, false },
        { 0, 4, 0, 7, true },
        { 2, 0, 3, 0, true },
      }
      api.nvim_helix_set_selections(0, original, 2, true)
      feed('>')
      eq({ '  one two', 'three', '  four', 'five' }, api.nvim_buf_get_lines(0, 0, -1, true))
      eq({ 'one', 'two', 'four\n' }, selected())
      eq(2, api.nvim_helix_get_state(0).primary)
      eq('h', api.nvim_get_mode().mode)
      feed('u')
      eq({ 'one two', 'three', 'four', 'five' }, api.nvim_buf_get_lines(0, 0, -1, true))
      eq(original, api.nvim_helix_get_state(0).selections)
      feed('2>')
      eq({ '    one two', 'three', '    four', 'five' }, api.nvim_buf_get_lines(0, 0, -1, true))
      feed('<lt>')
      eq({ '  one two', 'three', '  four', 'five' }, api.nvim_buf_get_lines(0, 0, -1, true))
      feed('u')
      eq({ '    one two', 'three', '    four', 'five' }, api.nvim_buf_get_lines(0, 0, -1, true))
    end
  )

  it(
    'joins selected lines through native whitespace rules and restores ranges with undo',
    function()
      text({ 'hello', '  world', 'next' })
      command('set helix nojoinspaces')
      local original = { { 0, 0, 1, 7, true } }
      api.nvim_helix_set_selections(0, original, 1, false)
      feed('J')
      eq({ 'hello world', 'next' }, api.nvim_buf_get_lines(0, 0, -1, true))
      eq({ 'hello world' }, selected())
      eq(true, api.nvim_helix_get_state(0).selections[1][5])
      feed('u')
      eq({ 'hello', '  world', 'next' }, api.nvim_buf_get_lines(0, 0, -1, true))
      eq(original, api.nvim_helix_get_state(0).selections)
    end
  )

  it('joins disjoint cursor lines once each and undoes the whole operation', function()
    text({ 'one', 'two', 'three', 'four' })
    command('set helix nojoinspaces')
    local original = { { 0, 0, 0, 3, false }, { 2, 0, 2, 5, true } }
    api.nvim_helix_set_selections(0, original, 2, false)
    feed('J')
    eq({ 'one two', 'three four' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'one', 'three' }, selected())
    eq(2, api.nvim_helix_get_state(0).primary)
    feed('u')
    eq({ 'one', 'two', 'three', 'four' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq(original, api.nvim_helix_get_state(0).selections)
    api.nvim_win_set_cursor(0, { 4, 0 })
    local tick = api.nvim_buf_get_changedtick(0)
    feed('J')
    eq(tick, api.nvim_buf_get_changedtick(0))
  end)

  it('uses upstream cursor contexts during insertion and returns ownership after Escape', function()
    text({ 'one', 'two' })
    command('set helix')
    feed('CiX')
    eq(
      1,
      exec_lua([[
      local ns = vim.api.nvim_create_namespace('nvim.multicursor')
      return #vim.api.nvim_buf_get_extmarks(0, ns, 0, -1, {})
    ]])
    )
    feed('<Esc>')
    eq({ 'Xone', 'Xtwo' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'X', 'X' }, selected())
    eq(
      0,
      exec_lua([[
      local ns = vim.api.nvim_create_namespace('nvim.multicursor')
      return #vim.api.nvim_buf_get_extmarks(0, ns, 0, -1, {})
    ]])
    )
    feed('u')
    eq({ 'one', 'two' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'o', 't' }, selected())
  end)

  it(
    'completes changes inside differently sized surrounds on the same line at every cursor',
    function()
      text({ '(a) (longer)' })
      command('set helix completeopt=menu,menuone,noselect')
      api.nvim_helix_set_selections(0, { { 0, 1, 0, 2, false }, { 0, 7, 0, 8, true } }, 2, false)
      feed('mimche')
      exec_lua([[vim.fn.complete(vim.fn.col('.') - 2, {'hello', 'help'})]])
      feed('<C-n><C-y><Esc>')
      eq('(hello) (hello)', api.nvim_get_current_line())
      eq(2, #api.nvim_helix_get_state(0).selections)
      eq(2, api.nvim_helix_get_state(0).primary)
      feed('u')
      eq('(a) (longer)', api.nvim_get_current_line())
      eq({ 'a', 'longer' }, selected())
      feed('U')
      eq('(hello) (hello)', api.nvim_get_current_line())
    end
  )

  it('accepts a built-in LSP completion at every compatible selection', function()
    text({ '(a) (longer)' })
    command('set helix completeopt=menu,menuone,noselect')
    exec_lua([[
      vim.lsp.start({
        name = 'helix-completion', root_dir = vim.uv.cwd(),
        cmd = function()
          local closed = false
          return {
            request = function(method, _, callback)
              if method == 'initialize' then
                callback(nil, {capabilities={completionProvider={}, textDocumentSync=1}})
              elseif method == 'textDocument/completion' then
                callback(nil, {{label='hello'}, {label='help'}})
              else
                callback(nil, nil)
              end
              return true, 1
            end,
            notify = function() return true end,
            is_closing = function() return closed end,
            terminate = function() closed = true end,
          }
        end,
        on_attach = function(client, buf)
          vim.lsp.completion.enable(true, client.id, buf, {autotrigger=false})
          vim.g.helix_lsp_attached = true
        end,
      })
    ]])
    t.retry(100, 3000, function()
      eq(true, exec_lua('return vim.g.helix_lsp_attached'))
    end)
    api.nvim_helix_set_selections(0, { { 0, 1, 0, 2, false }, { 0, 7, 0, 8, true } }, 2, false)
    feed('mimche')
    exec_lua('vim.lsp.completion.get()')
    t.retry(100, 3000, function()
      eq(1, n.fn.pumvisible())
    end)
    feed('<C-n><C-y><Esc>')
    eq('(hello) (hello)', api.nvim_get_current_line())
    eq({ 'o', 'o' }, selected())
    eq(2, api.nvim_helix_get_state(0).primary)
    feed('u')
    eq('(a) (longer)', api.nvim_get_current_line())
    eq({ 'a', 'longer' }, selected())
  end)

  it('resolves externally moved selections before native line insertion', function()
    text({ '  one', '    two' })
    command('set helix autoindent expandtab shiftwidth=2')
    api.nvim_helix_set_selections(0, { { 0, 2, 0, 5, false }, { 1, 4, 1, 7, false } }, 2, false)
    api.nvim_buf_set_lines(0, 0, 0, true, { 'prefix' })
    feed('oX<Esc>')
    eq({ 'prefix', '  one', '  X', '    two', '    X' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'X', 'X' }, selected())
  end)

  it(
    'rejects replacing selections during native insertion without losing the active cursors',
    function()
      text({ 'one', 'two' })
      command('set helix')
      feed('CiX')
      local ok, err = pcall(api.nvim_helix_set_selections, 0, { { 0, 0, 0, 1, false } }, 1, false)
      eq(false, ok)
      matches('Cannot replace Helix selections during native insertion', err)
      feed('Y<Esc>')
      eq({ 'XYone', 'XYtwo' }, api.nvim_buf_get_lines(0, 0, -1, true))
      eq({ 'Y', 'Y' }, selected())
      feed('u')
      eq({ 'one', 'two' }, api.nvim_buf_get_lines(0, 0, -1, true))
    end
  )

  it('returns native insertion contexts to their original buffer after a buffer switch', function()
    text({ 'one', 'two' })
    command('set helix hidden')
    local original = api.nvim_get_current_buf()
    local other = api.nvim_create_buf(true, false)
    feed('CiX')
    api.nvim_set_current_buf(other)
    feed('<Esc>')
    api.nvim_set_current_buf(original)
    eq({ 'Xone', 'Xtwo' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq(2, #api.nvim_helix_get_state(0).selections)
    eq({ 'X', 'X' }, selected())
    feed('l')
    eq(2, #api.nvim_helix_get_state(0).selections)
  end)

  it('retains the originating window selections when insertion ends in another window', function()
    text({ 'one', 'two' })
    command('set helix')
    local other = api.nvim_get_current_win()
    command('vsplit')
    local original = api.nvim_get_current_win()
    feed('CiX')
    api.nvim_set_current_win(other)
    feed('<Esc>')
    eq({ 'Xone', 'Xtwo' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq(2, #api.nvim_helix_get_state(original).selections)
    api.nvim_set_current_win(original)
    eq({ 'X', 'X' }, selected())
    feed('l')
    eq(2, #api.nvim_helix_get_state(0).selections)
  end)

  it('reports a real mode and isolates normal-mode mappings', function()
    text({ 'one two three' })
    command('nnoremap w dd')
    command('set helix')
    eq('h', api.nvim_get_mode().mode)
    eq({}, api.nvim_get_keymap('h'))
    feed('w')
    eq({ 'one ' }, selected())
    eq('one two three', api.nvim_get_current_line())
  end)

  it('advances repeated w through spaces, punctuation, lines and EOF', function()
    text({ 'one two three' })
    command('set helix')
    feed('w')
    eq({ 'one ' }, selected())
    feed('w')
    eq({ 'two ' }, selected())
    feed('w')
    eq({ 'three' }, selected())
    feed('www')
    eq({ 'three' }, selected())
    text({ 'one,  two', 'three' })
    feed('w')
    eq({ 'one' }, selected())
    feed('w')
    eq({ ',  ' }, selected())
    feed('w')
    eq({ 'two' }, selected())
    feed('w')
    eq({ 'three' }, selected())
  end)

  it('selects the closest surround with mim and arbitrary delimiters with ma/', function()
    text({ 'outer([hello])' })
    command('set helix')
    api.nvim_win_set_cursor(0, { 1, 8 })
    feed('mim')
    eq({ 'hello' }, selected())
    feed('mam')
    eq({ '[hello]' }, selected())
    text({ 'let r = /abc/;' })
    api.nvim_win_set_cursor(0, { 1, 10 })
    feed('ma/')
    eq({ '/abc/' }, selected())
  end)

  it('does not retain the previous word first character when moving backward', function()
    text({ 'helos sadf saf d' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 11, 0, 14, true } }, 1, false)
    eq({ 'saf' }, selected())
    eq({ 1, 11 }, api.nvim_win_get_cursor(0))
    feed('b')
    eq({ 'sadf ' }, selected())
    eq({ { 0, 6, 0, 11, true } }, api.nvim_helix_get_state(0).selections)
    eq({ 1, 6 }, api.nvim_win_get_cursor(0))
    feed('cX<Esc>')
    eq('helos Xsaf d', api.nvim_get_current_line())
    feed('u')
    eq('helos sadf saf d', api.nvim_get_current_line())
    eq({ 'sadf ' }, selected())
    feed('b')
    eq({ 'helos ' }, selected())
    feed('bb')
    eq({ 'helos ' }, selected())
  end)

  it('does not retain the previous word last character when moving to word ends', function()
    text({ 'one two three' })
    command('set helix')
    feed('e')
    eq({ 'one' }, selected())
    feed('e')
    eq({ ' two' }, selected())
    feed('e')
    eq({ ' three' }, selected())
    feed('eee')
    eq({ ' three' }, selected())
  end)

  it('clears the previous word first character on screen when moving backward', function()
    local screen = Screen.new(32, 5)
    text({ 'helos sadf saf d' })
    command('set helix noshowmode')
    feed('wwwbb')
    screen:expect([[
      helos {17:^sadf }saf d                |
      {1:~                               }|*3
                                      |
    ]])
    feed('b')
    screen:expect([[
      {17:^helos }sadf saf d                |
      {1:~                               }|*3
                                      |
    ]])
  end)

  it('replaces word selections when changing direction in normal mode', function()
    text({ 'one two three four' })
    command('set helix')
    for _, step in ipairs({
      { 'w', 'one ', false },
      { 'w', 'two ', false },
      { 'b', 'two ', true },
      { 'b', 'one ', true },
      { 'w', 'one ', false },
      { 'e', ' two', false },
      { 'e', ' three', false },
      { 'b', 'three', true },
      { 'b', 'two ', true },
    }) do
      feed(step[1])
      eq('h', api.nvim_get_mode().mode)
      eq({ step[2] }, selected())
      eq(step[3], api.nvim_helix_get_state(0).selections[1][5])
    end
  end)

  it('applies word counts to the final motion and preserves ranges at file boundaries', function()
    text({ 'one two three four' })
    command('set helix')
