local t = require('test.testutil')
local n = require('test.functional.testnvim')()
local Screen = require('test.functional.ui.screen')
local eq, matches = t.eq, t.matches
local api, command, feed, exec_lua = n.api, n.command, n.feed, n.exec_lua

local function text(lines)
  api.nvim_buf_set_lines(0, 0, -1, true, lines)
  api.nvim_win_set_cursor(0, { 1, 0 })
end

local function selected()
  return exec_lua([[
    local values = {}
    for _, s in ipairs(vim.api.nvim_helix_get_state(0).selections) do
      values[#values + 1] = table.concat(vim.api.nvim_buf_get_text(0, s[1], s[2], s[3], s[4], {}), '\n')
    end
    return values
  ]])
end

describe('native Helix mode', function()
  before_each(function()
    n.clear()
  end)

  it('is opt-in and retains ordinary Vim behavior by default', function()
    eq(false, api.nvim_get_option_value('helix', {}))
    text({ 'one two three' })
    feed('w')
    eq('n', api.nvim_get_mode().mode)
    eq({ 1, 4 }, api.nvim_win_get_cursor(0))
    feed('dw')
    eq('one three', api.nvim_get_current_line())
  end)

  it('reports a real mode and isolates normal-mode mappings', function()
    text({ 'one two three' })
    command('nnoremap w dd')
    command('set helix')
    eq('h', api.nvim_get_mode().mode)
    eq({}, api.nvim_get_keymap('h'))
    feed('w')
    eq({ 'one ' }, selected())
    eq('one two three', api.nvim_get_current_line())
  end)

  it('advances repeated w through spaces, punctuation, lines and EOF', function()
    text({ 'one two three' })
    command('set helix')
    feed('w')
    eq({ 'one ' }, selected())
    feed('w')
    eq({ 'two ' }, selected())
    feed('w')
    eq({ 'three' }, selected())
    feed('www')
    eq({ 'three' }, selected())
    text({ 'one,  two', 'three' })
    feed('w')
    eq({ 'one' }, selected())
    feed('w')
    eq({ ',  ' }, selected())
    feed('w')
    eq({ 'two' }, selected())
    feed('w')
    eq({ 'three' }, selected())
  end)

  it('selects the closest surround with mim and arbitrary delimiters with ma/', function()
    text({ 'outer([hello])' })
    command('set helix')
    api.nvim_win_set_cursor(0, { 1, 8 })
    feed('mim')
    eq({ 'hello' }, selected())
    feed('mam')
    eq({ '[hello]' }, selected())
    text({ 'let r = /abc/;' })
    api.nvim_win_set_cursor(0, { 1, 10 })
    feed('ma/')
    eq({ '/abc/' }, selected())
  end)

  it('changes text through native Insert mode and restores selections with undo', function()
    text({ 'outer([hello])' })
    command('set helix')
    api.nvim_win_set_cursor(0, { 1, 8 })
    feed('mimcworld<Esc>')
    eq('outer([world])', api.nvim_get_current_line())
    eq('h', api.nvim_get_mode().mode)
    feed('u')
    eq('outer([hello])', api.nvim_get_current_line())
    eq({ 'hello' }, selected())
    feed('U')
    eq('outer([world])', api.nvim_get_current_line())
    eq({ 'd' }, selected())
  end)

  it('edits multiple selections and restores text and selection identity together', function()
    text({ 'one', 'two' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 1, 0, 1, 3, true } }, 2, false)
    feed('cXY<Esc>')
    eq({ 'XY', 'XY' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq(2, api.nvim_helix_get_state(0).primary)
    feed('u')
    eq({ 'one', 'two' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'one', 'two' }, selected())
    eq(true, api.nvim_helix_get_state(0).selections[2][5])
    feed('U')
    eq({ 'XY', 'XY' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq({ 'Y', 'Y' }, selected())
  end)

  it('adds cursors with C, selects lines with x, and types at every cursor', function()
    text({ 'one', 'two', 'three' })
    command('set helix')
    feed('CCx')
    eq(3, #api.nvim_helix_get_state(0).selections)
    feed('cZ<Esc>')
    -- Deleting adjacent ranges coalesces identical insertion gaps.
    eq('Z', table.concat(api.nvim_buf_get_lines(0, 0, -1, true), '\n'))
    feed('u')
    eq({ 'one', 'two', 'three' }, api.nvim_buf_get_lines(0, 0, -1, true))
  end)

  it('keeps actual Insert events, cursor placement and insert mappings', function()
    text({ '' })
    exec_lua([[
      _G.helix_events = {}
      vim.api.nvim_create_autocmd({'InsertEnter', 'InsertLeave'}, {
        callback = function(ev) table.insert(_G.helix_events, ev.event) end,
      })
      vim.keymap.set('i', '<F3>', 'hello')
      vim.o.helix = true
    ]])
    feed('iY')
    eq('i', api.nvim_get_mode().mode)
    eq({ 1, 1 }, api.nvim_win_get_cursor(0))
    feed('<F3><Esc>')
    eq('Yhello', api.nvim_get_current_line())
    eq({ 'InsertEnter', 'InsertLeave' }, exec_lua('return _G.helix_events'))
  end)

  it('supports a configurable h mapping and native mode extension', function()
    text({ '(hello)' })
    exec_lua([[
      vim.o.helix = true
      _G.helix_mapping_modes = {}
      vim.keymap.set('h', 'Q', function()
        table.insert(_G.helix_mapping_modes, vim.fn.mode(1))
        vim.helix.textobject('m')
      end)
      vim.keymap.set('h', '<F4>', '<Cmd>lua table.insert(_G.helix_mapping_modes, vim.fn.mode(1))<CR>')
      vim.keymap.set('h', '<F5>', function()
        vim.cmd('normal! v')
        table.insert(_G.helix_mapping_modes, vim.fn.mode(1))
      end)
    ]])
    api.nvim_win_set_cursor(0, { 1, 3 })
    feed('Q')
    eq({ 'hello' }, selected())
    eq('h', api.nvim_get_keymap('h')[1].mode)
    feed(';vl')
    eq('hv', api.nvim_get_mode().mode)
    feed('<F4>')
    eq({ 'h', 'hv' }, exec_lua('return _G.helix_mapping_modes'))
    feed('<Esc>')
    eq('h', api.nvim_get_mode().mode)
    feed('<F5>')
    eq('v', api.nvim_get_mode().mode)
    eq({ 'h', 'hv', 'v' }, exec_lua('return _G.helix_mapping_modes'))
    feed('<Esc>')
    eq('h', api.nvim_get_mode().mode)
  end)

  it('validates an entire edit request before changing text', function()
    text({ 'abc def' })
    command('set helix')
    local err = t.pcall_err(api.nvim_helix_apply_edits, {
      { 0, 0, 0, 1, { 'X' } },
      { 8, 0, 8, 1, { 'Y' } },
    }, false)
    matches('Invalid Helix position', err)
    eq('abc def', api.nvim_get_current_line())
    err = t.pcall_err(
      api.nvim_helix_set_selections,
      0,
      { { 0, 0, 0, 3, false }, { 0, 2, 0, 4, false } },
      1,
      false
    )
    matches('non%-overlapping', err)
  end)

  it('uses ordinary Vim mode in special buffers and allows toggling off', function()
    text({ 'abc' })
    command('set helix')
    eq('h', api.nvim_get_mode().mode)
    command('setlocal buftype=nofile')
    eq('n', api.nvim_get_mode().mode)
    command('setlocal buftype=')
    eq('h', api.nvim_get_mode().mode)
    command('set nohelix')
    eq('n', api.nvim_get_mode().mode)
    feed('x')
    eq('bc', api.nvim_get_current_line())
  end)

  it('preserves independent window selections and tracks unrelated API edits', function()
    text({ 'one two three' })
    command('set helix')
    feed('w')
    local first = api.nvim_get_current_win()
    command('vsplit')
    local second = api.nvim_get_current_win()
    api.nvim_win_set_cursor(second, { 1, 4 })
    feed('w')
    eq({ 'two ' }, selected())
    api.nvim_buf_set_text(0, 0, 0, 0, 0, { 'X' })
    eq({ 0, 1, 0, 5, false }, api.nvim_helix_get_state(first).selections[1])
    api.nvim_set_current_win(first)
    eq({ 'one ' }, selected())
    command('close')
    eq(second, api.nvim_get_current_win())
    eq({ 'two ' }, selected())
  end)

  it('pastes into all selections through the ordinary paste API', function()
    text({ 'one two' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 0, 4, 0, 7, false } }, 1, false)
    eq(true, api.nvim_paste('X', false, -1))
    eq('X X', api.nvim_get_current_line())
    feed('u')
    eq('one two', api.nvim_get_current_line())
  end)

  it('renders selections with normal and insert cursor shapes', function()
    local screen = Screen.new(32, 5)
    text({ '(hello)' })
    command('set helix noshowmode')
    api.nvim_win_set_cursor(0, { 1, 3 })
    feed('mim')
    screen:expect({
      grid = [[
      ({17:hell^o})                         |
      {1:~                               }|*3
                                      |
    ]],
      mode = 'normal',
    })
    feed('cX')
    screen:expect({
      grid = [[
      (X^)                             |
      {1:~                               }|*3
                                      |
    ]],
      mode = 'insert',
    })
    eq('i', api.nvim_get_mode().mode)
    eq({ 1, 2 }, api.nvim_win_get_cursor(0))
    feed('<Esc>')
    eq('(X)', api.nvim_get_current_line())
    n.assert_alive()
  end)

  it('moves and deletes complete Unicode graphemes', function()
    text({ 'á👩‍💻z' })
    command('set helix')
    eq({ 'á' }, selected())
    feed('l')
    eq({ '👩‍💻' }, selected())
    feed('d')
    eq('áz', api.nvim_get_current_line())
    feed('u')
    eq('á👩‍💻z', api.nvim_get_current_line())
    eq({ '👩‍💻' }, selected())
    feed('h')
    eq({ 'á' }, selected())
  end)

  it('preserves the desired column across consecutive vertical motions', function()
    text({ 'abcdef', 'a', 'abcdef' })
    command('set helix')
    api.nvim_win_set_cursor(0, { 1, 4 })
    feed('jj')
    eq({ 3, 4 }, api.nvim_win_get_cursor(0))
  end)

  it('handles multicursor backspace, newline, indentation and insert mappings', function()
    text({ '  a', '  b' })
    command('set helix autoindent expandtab tabstop=2 shiftwidth=2')
    api.nvim_helix_set_selections(0, { { 0, 2, 0, 3, false }, { 1, 2, 1, 3, false } }, 2, false)
    exec_lua([[vim.keymap.set('i', '(', '()<Left>')]])
    feed('i(X<BS>Y<Right><CR>Z<Esc>')
    eq({ '  (Y)', '  Za', '  (Y)', '  Zb' }, api.nvim_buf_get_lines(0, 0, -1, true))
    feed('u')
    eq({ '  a', '  b' }, api.nvim_buf_get_lines(0, 0, -1, true))
  end)

  it('runs InsertCharPre once and applies its replacement at every cursor', function()
    text({ 'a', 'b' })
    command('set helix')
    exec_lua([[
      _G.helix_pre = 0
      vim.api.nvim_create_autocmd('InsertCharPre', {callback=function()
        _G.helix_pre = _G.helix_pre + 1
        if vim.v.char == 'x' then vim.v.char = 'XY' end
      end})
    ]])
    feed('Ci' .. 'x<Esc>')
    eq({ 'XYa', 'XYb' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq(1, exec_lua('return _G.helix_pre'))
  end)

  it('uses native completion and keeps one explicit completion context', function()
    text({ '', '' })
    command('set helix completeopt=menu,menuone,noselect')
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 0, false }, { 1, 0, 1, 0, false } }, 2, false)
    feed('ihe')
    eq({ 'he', 'he' }, api.nvim_buf_get_lines(0, 0, -1, true))
    exec_lua([[vim.fn.complete(1, {'hello', 'help'})]])
    eq(1, #api.nvim_helix_get_state(0).selections)
    feed('<C-n><C-y><Esc>')
    eq({ 'he', 'hello' }, api.nvim_buf_get_lines(0, 0, -1, true))
    eq('h', api.nvim_get_mode().mode)
  end)

  it('supports built-in snippet placeholders in a native Helix buffer', function()
    text({ '' })
    command('set helix')
    feed('i')
    exec_lua([[vim.snippet.expand('hello ${1:world}!$0')]])
    eq('s', api.nvim_get_mode().mode)
    feed('there')
    eq('hello there!', api.nvim_get_current_line())
    exec_lua('vim.snippet.jump(1)')
    feed('<Esc>')
    eq('h', api.nvim_get_mode().mode)
    eq('hello there!', api.nvim_get_current_line())
  end)

  it('uses native undo branches across several distinct commands', function()
    text({ 'abc' })
    command('set helix')
    feed('iX<Esc>liY<Esc>')
    eq('XYabc', api.nvim_get_current_line())
    feed('u')
    eq('Xabc', api.nvim_get_current_line())
    feed('u')
    eq('abc', api.nvim_get_current_line())
    feed('UU')
    eq('XYabc', api.nvim_get_current_line())
    feed('uiZ<Esc>')
    eq('XZabc', api.nvim_get_current_line())
    feed('uU')
    eq('XZabc', api.nvim_get_current_line())
  end)

  it('selects regex matches and applies one edit to every match', function()
    text({ 'one two one' })
    command('set helix')
    feed('%')
    exec_lua([[vim.helix.select('one')]])
    eq({ 'one', 'one' }, selected())
    feed('cX<Esc>')
    eq('X two X', api.nvim_get_current_line())
    feed('u')
    eq({ 'one', 'one' }, selected())
    exec_lua([[vim.helix.select('^')]]) -- Zero-width anchors terminate.
    n.assert_alive()
  end)

  it('keeps native undo-file compatibility and safely wipes selection buffers', function()
    local file = t.tmpname()
    text({ 'abc' })
    command('set helix')
    feed('iX<Esc>')
    command('wundo! ' .. file)
    command('set nohelix')
    command('rundo ' .. file)
    command('undo')
    eq('abc', api.nvim_get_current_line())
    command('set helix')
    local buf = api.nvim_get_current_buf()
    command('enew!')
    api.nvim_buf_delete(buf, { force = true })
    command('vsplit')
    command('close')
    n.assert_alive()
    os.remove(file)
  end)

  it('loads the example configuration and exercises its native mappings', function()
    exec_lua([[dofile(...)]], t.paths.test_source_path .. '/contrib/helix/init.lua')
    eq(true, api.nvim_get_option_value('helix', {}))
    text({ '(hello)' })
    api.nvim_win_set_cursor(0, { 1, 3 })
    feed('mim')
    eq({ 'hello' }, selected())
    matches('HELIX NORMAL', exec_lua('return vim.helix.statusline()'))
    local first = api.nvim_get_current_buf()
    command('enew!')
    feed('<Space>p')
    eq(first, api.nvim_get_current_buf())
    eq('h', api.nvim_get_mode().mode)
  end)

  it('searches with /, n, N and wraps around the buffer', function()
    text({ 'one two one three one' })
    command('set helix')
    feed('/one<CR>')
    eq({ 1, 10 }, api.nvim_win_get_cursor(0))
    feed('n')
    eq({ 1, 20 }, api.nvim_win_get_cursor(0))
    feed('n')
    eq({ 1, 2 }, api.nvim_win_get_cursor(0))
    feed('N')
    eq({ 1, 20 }, api.nvim_win_get_cursor(0))
    eq({ 'one' }, selected())
  end)

  it('uses named registers and preserves per-selection yank values', function()
    text({ 'one two' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 0, 4, 0, 7, false } }, 1, false)
    feed('"ay"ap')
    eq('oneone twotwo', api.nvim_get_current_line())
    eq('one\ntwo', n.fn.getreg('a'))
    n.fn.setreg('a', 'EXT')
    feed('"aR')
    eq('oneEXT twoEXT', api.nvim_get_current_line())
  end)

  it('normalizes selections after external deletion brings gaps together', function()
    text({ 'one two' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 0, 4, 0, 7, true } }, 2, false)
    api.nvim_buf_set_text(0, 0, 0, 0, 7, { '' })
    eq({ { 0, 0, 0, 0, true } }, api.nvim_helix_get_state(0).selections)
    eq(1, api.nvim_helix_get_state(0).primary)
    n.assert_alive()
  end)

  it('respects explicit Vim normal commands and cursor() jumps', function()
    text({ 'one two three' })
    command('set helix')
    command('normal! w')
    eq({ 1, 4 }, api.nvim_win_get_cursor(0))
    eq({ 't' }, selected())
    n.fn.cursor(1, 9)
    eq({ 't' }, selected())
    eq({ 1, 8 }, api.nvim_win_get_cursor(0))
    n.fn.setpos('.', { 0, 1, 2, 0 })
    eq({ 'n' }, selected())
  end)

  it('supports a buffer-local exclusion and emits native mode changes', function()
    text({ 'abc' })
    exec_lua([[
      _G.helix_modes = {}
      vim.api.nvim_create_autocmd('ModeChanged', {callback=function()
        _G.helix_modes[#_G.helix_modes+1] = vim.v.event.new_mode
      end})
      vim.o.helix = true
    ]])
    eq('h', api.nvim_get_mode().mode)
    exec_lua('vim.b.helix = false')
    eq('n', api.nvim_get_mode().mode)
    exec_lua('vim.b.helix = true')
    eq('h', api.nvim_get_mode().mode)
    eq({ 'h', 'n', 'h' }, exec_lua('return _G.helix_modes'))
  end)

  it('streams paste as one transaction and cancels if its buffer changes', function()
    text({ 'one two' })
    command('set helix')
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 0, 4, 0, 7, false } }, 1, false)
    eq(true, api.nvim_paste('X', false, 1))
    eq('one two', api.nvim_get_current_line())
    eq(true, api.nvim_paste('Y', false, 3))
    eq('XY XY', api.nvim_get_current_line())
    feed('u')
    eq('one two', api.nvim_get_current_line())
    eq(true, api.nvim_paste('START', false, 1))
    command('enew!')
    eq(false, api.nvim_paste('END', false, 3))
    eq('', api.nvim_get_current_line())
  end)

  it('pastes into a search prompt without editing the document', function()
    text({ 'one two one' })
    command('set helix')
    feed('/')
    eq('c', api.nvim_get_mode().mode)
    eq(true, api.nvim_paste('one', false, -1))
    feed('<CR>')
    eq('one two one', api.nvim_get_current_line())
    eq({ 'one' }, selected())
    eq({ 1, 10 }, api.nvim_win_get_cursor(0))
  end)

  it('enables defaults through setup without configuring individual delimiters', function()
    text({ 'hello' })
    exec_lua('vim.helix.setup()')
    eq(true, api.nvim_get_option_value('helix', {}))
    feed('miwms(')
    eq('(hello)', api.nvim_get_current_line())
    feed('u')
    eq('hello', api.nvim_get_current_line())
    eq({ 'hello' }, selected())
    feed('ms/')
    eq('/hello/', api.nvim_get_current_line())
    feed('u')
    feed('ms"')
    eq('"hello"', api.nvim_get_current_line())
  end)

  it('accepts setup mappings as strings, callbacks and disabled keys', function()
    text({ 'hello' })
    exec_lua([[
      vim.g.mapleader = ' '
      vim.keymap.set('n', 'Q', 'dd')
      vim.helix.setup({keymaps={
        ['<leader>s'] = 'ms',
        Q = function() vim.helix.surround('"') end,
        w = false,
      }})
    ]])
    exec_lua("vim.helix.textobject('w')")
    feed(' s[')
    eq('[hello]', api.nvim_get_current_line())
    feed('uQ')
    eq('"hello"', api.nvim_get_current_line())
    feed('u')
    local before = api.nvim_helix_get_state(0).selections
    feed('w')
    eq(before, api.nvim_helix_get_state(0).selections)
    eq('hello', api.nvim_get_current_line())
  end)

  it('uses a custom pair for adding, selecting and undoing at all cursors', function()
    text({ 'one', 'two' })
    exec_lua([[vim.helix.setup({surrounds={t={'<em>', '</em>'}}})]])
    api.nvim_helix_set_selections(0, { { 0, 0, 0, 3, false }, { 1, 0, 1, 3, true } }, 2, false)
    feed('mst')
    eq({ '<em>one</em>', '<em>two</em>' }, api.nvim_buf_get_lines(0, 0, -1, true))
    feed('u')
    eq({ 'one', 'two' }, selected())
    eq(2, api.nvim_helix_get_state(0).primary)
    eq(true, api.nvim_helix_get_state(0).selections[2][5])
    feed('mstmim')
    eq({ 'one', 'two' }, selected())
    feed('mat')
    eq({ '<em>one</em>', '<em>two</em>' }, selected())
    feed('mit')
    eq({ 'one', 'two' }, selected())
  end)

  it('handles custom symmetric markers, nesting and duplicate pair aliases', function()
    exec_lua([[vim.helix.setup({surrounds={b={'**', '**'}, q={'"', '"'}, t={'<em>', '</em>'}}})]])
    text({ '**hello**' })
    api.nvim_win_set_cursor(0, { 1, 8 })
    feed('mib')
    eq({ 'hello' }, selected())
    feed('mab')
    eq({ '**hello**' }, selected())
    text({ '("hello")' })
    api.nvim_win_set_cursor(0, { 1, 4 })
    feed('2mim')
    eq({ '"hello"' }, selected())
    text({ '[<em>hello</em>]' })
    api.nvim_win_set_cursor(0, { 1, 7 })
    feed('mim')
    eq({ 'hello' }, selected())
    feed('2mim')
    eq({ '<em>hello</em>' }, selected())
    exec_lua([[vim.helix.setup({surrounds={['(']={'«', '»'}, ['é']={'【', '】'}}})]])
    text({ 'hello' })
    feed('miwms)')
    eq('«hello»', api.nvim_get_current_line())
    feed('mi(')
    eq({ 'hello' }, selected())
    text({ 'hello' })
    feed('miwmsé')
    eq('【hello】', api.nvim_get_current_line())
    feed('mié')
    eq({ 'hello' }, selected())
  end)

  it('validates setup before changing options, mappings or custom pairs', function()
    eq(
      true,
      exec_lua([[
      for _, opts in ipairs({
        {enabled='yes'}, {surrounds={c={'', '*/'}}},
        {surrounds={c={'/*', '*/', 'extra'}}},
        {surrounds={c={'/*\n', '*/'}}}, {surrounds={c={'/*', 42}}},
        {surrounds={word={'(', ')'}}}, {surrounds={m={'(', ')'}}},
        {keymaps={Q=42}}, {keymaps={['']='ms('}}, {unknown=true},
      }) do
